import { useMemo } from 'react';
import katex from 'katex';
import { useT } from '../i18n';
import 'katex/dist/katex.min.css';

export default function MathExpression({ expr, displayMode = false }) {
  const t = useT();
  const rendered = useMemo(() => {
    try {
      if (expr.length > 10000) throw new Error('Formula too large');
      return { html: katex.renderToString(expr, {
        displayMode,
        output: 'htmlAndMathml',
        throwOnError: true,
        strict: 'ignore',
        // Deny every trusted command explicitly, even if a surrounding page has
        // polluted Object.prototype. Bound macro expansion and extreme sizing.
        trust: () => false,
        macros: Object.create(null),
        maxExpand: 1000,
        maxSize: 20,
      }) };
    } catch {
      return { error: true };
    }
  }, [expr, displayMode]);
  const className = displayMode ? 'my-5 block max-w-full overflow-x-auto py-1 text-ink' : 'inline text-ink';
  if (rendered.error) {
    return (
      <span className={className} data-math-error="true">
        <span className="block text-xs text-error">{t('docs.mathError')}</span>
        <code className="whitespace-pre-wrap break-words font-mono text-xs">{expr}</code>
      </span>
    );
  }
  // The only HTML boundary: generated by KaTeX with trust disabled, never by the
  // Markdown renderer or the source. MathML supplies the accessible expression.
  return <span className={className} data-math-display={String(displayMode)} dangerouslySetInnerHTML={{ __html: rendered.html }} />;
}
